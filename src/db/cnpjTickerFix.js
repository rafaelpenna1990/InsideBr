// Quando tem mais de um ticker pra mesma empresa, prioriza o mais
// líquido/comum: units (11) > preferencial (4) > ordinária (3).
function pickBestTicker(rawTickers) {
  const options = rawTickers.split("/");
  const unit = options.find((t) => t.endsWith("11"));
  if (unit) return unit;
  const pref = options.find((t) => t.endsWith("4"));
  if (pref) return pref;
  return options[0];
}

async function main() {
  console.log(`Conferindo ${CNPJ_TICKER_LIST.length} empresas por CNPJ...`);
  let updated = 0;
  let unchanged = 0;
  let notFound = 0;

  for (const [cnpj, rawTickers] of CNPJ_TICKER_LIST) {
    const ticker = pickBestTicker(rawTickers);
    const existing = await pool.query("SELECT id, ticker, name FROM companies WHERE cnpj = $1", [
      cnpj,
    ]);

    if (existing.rows.length === 0) {
      notFound++;
      continue;
    }

    const company = existing.rows[0];
    if (company.ticker === ticker) {
      unchanged++;
      continue;
    }

    await pool.query("UPDATE companies SET ticker = $1 WHERE id = $2", [ticker, company.id]);
    console.log(
      `  ${company.name}: "${company.ticker || "(vazio)"}" → "${ticker}"`
    );
    updated++;
  }

  console.log(`\nAtualizadas: ${updated}`);
  console.log(`Já estavam certas: ${unchanged}`);
  console.log(`CNPJ não encontrado no nosso banco: ${notFound}`);

  const totalResult = await pool.query(
    "SELECT COUNT(*) AS total, COUNT(ticker) AS com_ticker FROM companies"
  );
  console.log("\nTotais finais:", totalResult.rows[0]);

  await pool.end();
}

main().catch((err) => {
  console.error("Erro:", err.message);
  process.exit(1);
});
